"""Generate every number, table and figure used in paper/ from results/.

Usage: python scripts/make_paper_assets.py --results results --paper paper
Writes paper/generated/numbers.tex (LaTeX macros), paper/generated/table_*.tex
and paper/figures/*.pdf. The paper never contains a hand-typed result.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np


def pct(x: float) -> str:
    return f"{100 * x:.0f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--paper", default="paper")
    a = ap.parse_args()
    res, paper = Path(a.results), Path(a.paper)
    (paper / "generated").mkdir(parents=True, exist_ok=True)
    (paper / "figures").mkdir(parents=True, exist_ok=True)

    S = json.loads((res / "structural.json").read_text())
    P = S["projects"]
    multi = [p for p in P if p["duty"]["k_star"] > 1]
    single = [p for p in P if p["duty"]["k_star"] == 1]
    red = [p["duty"]["cut_reduction_vs_random"] for p in multi]
    cf_err = max(abs(p["duty"]["random_cut_expected_closed_form"] - p["duty"]["random_cut_mean"])
                 / p["duty"]["random_cut_mean"] for p in multi)
    langs = {l: sum(p["language"] == l for p in multi) for l in ("python", "cpp", "java", "javascript")}
    ref = json.loads((res / "reference_tests.json").read_text()) if (res / "reference_tests.json").exists() else []

    def full_pass(r):
        ts = [r[k] for k in ("unit_test", "acceptance_test") if k in r]
        return ts and all(t["failed"] == 0 and t["errors"] == 0 and t["passed"] > 0 for t in ts)

    ref_full = [r for r in ref if full_pass(r)]
    nums = {
        "NProjects": len(P),
        "NMulti": len(multi),
        "NSingle": len(single),
        "NMultiPython": langs["python"], "NMultiCpp": langs["cpp"],
        "NMultiJava": langs["java"], "NMultiJS": langs["javascript"],
        "CutRedMin": pct(min(red)), "CutRedMax": pct(max(red)),
        "CutRedMedian": pct(float(np.median(red))),
        "PMax": f"{max(p['duty']['p_random'] for p in multi):.4f}",
        "Draws": f"{S['meta']['draws']:,}".replace(",", "{,}"),
        "Seed": S["meta"]["seed"],
        "CFErr": f"{100 * cf_err:.1f}",
        "NBeatGC": sum(p["duty"]["criterion_mq_minus_gc_mq"] > 1e-9 for p in multi),
        "NEqGC": sum(p["duty"]["ari_vs_one_per_class"] > 0.999 for p in multi),
        "NSplitClass": sum(p["duty"]["splits_a_class"] for p in P),
        "NInfomapSame": sum(p["duty"]["ari_vs_infomap"] > 0.999 for p in multi),
        "NInfomapClose": sum(p["duty"]["ari_vs_infomap"] >= 0.75 for p in multi),
        "NInfomapSameK": sum(p["duty"]["infomap_k"] == p["duty"]["k_star"] for p in multi),
        "NLouvainSameK": sum(p["duty"]["louvain_k"] == p["duty"]["k_star"] for p in multi),
        "NLambdaChange": sum(len(set(p["duty"]["k_by_lambda"].values())) > 1 for p in P),
        "WeightStableAll": pct(np.mean([p["duty"]["weight_grid"]["same_k_share"] for p in P])),
        "WeightStableMulti": pct(np.mean([p["duty"]["weight_grid"]["same_k_share"] for p in multi])),
        "WeightARIMulti": f"{np.mean([p['duty']['weight_grid']['mean_ari_vs_default'] for p in multi]):.2f}",
        "NClassLevelMulti": sum(p["class"]["k_star"] > 1 for p in P),
        "KMin": min(p["duty"]["k_star"] for p in multi),
        "KMax": max(p["duty"]["k_star"] for p in multi),
        "DutyMin": min(p["duty"]["n"] for p in P), "DutyMax": max(p["duty"]["n"] for p in P),
        "NRefRan": sum(1 for r in ref if "unit_test" in r), "NRefFull": len(ref_full),
        "DevBenchCommit": S["meta"]["devbench_commit"][:7],
        "PythonVersion": S["meta"]["python"], "NumpyVersion": S["meta"]["numpy"],
    }
    lines = ["% AUTO-GENERATED by scripts/make_paper_assets.py -- do not edit by hand"]
    for k, v in nums.items():
        lines.append(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}")
    (paper / "generated" / "numbers.tex").write_text("\n".join(lines) + "\n")

    # Table: multi-agent projects
    short = {"cpp": "C++", "java": "Java", "javascript": "JS", "python": "Py"}
    rows = []
    for p in sorted(multi, key=lambda p: (p["language"], p["project"])):
        d = p["duty"]
        name = p["project"].replace("_", r"\_")
        rows.append(
            f"{name} & {short[p['language']]} & {d['n_classes']} & {d['n']} & {d['k_star']} & "
            f"{'+'.join(map(str, d['sizes']))} & {pct(d['cut_reduction_vs_random'])} & "
            f"{d['p_random']:.4f} & {d['criterion_mq_minus_gc_mq']:+.2f} & {d['ari_vs_infomap']:.2f} & "
            f"{d['weight_grid']['same_k']}/81 \\\\")
    tab = [r"\begin{tabular}{@{}llrrrlrrrrr@{}}", r"\toprule",
           r"Project & Lang & Cls & $n$ & $k^\ast$ & Sizes & Cut$\downarrow$\% & $p$ & $\Delta$MQ$_{\text{GC}}$ & ARI$_{\text{IM}}$ & Stable \\",
           r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]
    (paper / "generated" / "table_multi.tex").write_text("\n".join(tab) + "\n")

    single_names = ", ".join(sorted(p["project"].replace("_", r"\_") + f" ({p['duty']['n']})" for p in single))
    (paper / "generated" / "single_list.tex").write_text(single_names + "\n")

    # Reference-test table
    if ref:
        rr = []
        for r in ref:
            name = r["project"].split("/")[1].replace("_", r"\_")
            if "status" in r:
                rr.append(f"{name} & \\multicolumn{{2}}{{l}}{{skipped here; 5/13 on Colab}} \\\\")
                continue
            cells = []
            for k in ("unit_test", "acceptance_test"):
                t = r.get(k)
                cells.append("--" if t is None else f"{t['passed']}/{t['passed'] + t['failed'] + t['errors']}")
            rr.append(f"{name} & {cells[0]} & {cells[1]} \\\\")
        reft = [r"\begin{tabular}{@{}lrr@{}}", r"\toprule", r"Project & Unit & Acceptance \\", r"\midrule",
                *rr, r"\bottomrule", r"\end{tabular}"]
        (paper / "generated" / "table_reference.tex").write_text("\n".join(reft) + "\n")

    # Figures
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "pdf.fonttype": 42, "ps.fonttype": 42})

    pick = [p for p in multi if p["project"] in ("graph-cpp", "redis-cache", "stocktrends", "Actor_relationship_game")]
    fig, axes = plt.subplots(1, len(pick), figsize=(6.75, 1.55))
    for ax, p in zip(np.atleast_1d(axes), pick):
        cur = p["duty"]["mq_curve"]
        ks = sorted(map(int, cur))
        ax.plot(ks, [cur[str(k)] if isinstance(next(iter(cur)), str) else cur[k] for k in ks], color="#3B6D11", lw=1.2)
        ax.axvline(p["duty"]["k_star"], color="#5F5E5A", ls="--", lw=0.8)
        ax.set_title(f"{p['project'].replace('_relationship_game', '')} ($k^*$={p['duty']['k_star']})", fontsize=8)
        ax.set_xlabel("agents $k$")
        ax.tick_params(labelsize=7)
    np.atleast_1d(axes)[0].set_ylabel("MQ")
    fig.tight_layout(pad=0.3)
    fig.savefig(paper / "figures" / "mq_curves.pdf")

    fig, ax = plt.subplots(figsize=(3.25, 2.0))
    order = sorted(multi, key=lambda p: p["duty"]["cut_reduction_vs_random"])
    y = np.arange(len(order))
    ratio = [p["duty"]["cut"] / p["duty"]["random_cut_mean"] for p in order]
    ax.barh(y, [1.0] * len(order), height=0.6, color="#D3D1C7", label="random team, same sizes (= 1)")
    ax.barh(y, ratio, height=0.6, color="#3B6D11", label="criterion team")
    ax.set_yticks(y, [p["project"].replace("_relationship_game", "").replace("-frontend", "") for p in order], fontsize=6.5)
    ax.set_xlim(0, 1.0)
    ax.set_xlabel("cross-agent dependency, relative to random")
    ax.legend(fontsize=6, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.22), ncol=2)
    fig.tight_layout(pad=0.3)
    fig.savefig(paper / "figures" / "cut_vs_random.pdf")
    print(json.dumps(nums, indent=1))


if __name__ == "__main__":
    main()
